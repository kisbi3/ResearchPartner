"""Scaffold a Physics Research Harness project in the current directory.

After v3 the project root IS the research root — there is no
`ResearchPartner-runs/<date>-<slug>/` wrapping directory anymore. This
script creates the harness directory tree directly inside the project
and writes a `.research-harness` marker file at the root so every gate
script can locate the project from any subdirectory.

For a single-thread project (most common) you run this once from the
project root and never again::

    cd MyPhysicsProject
    python <path-to-harness>/.harness/scripts/init_research_project.py

For a multi-thread project where you want two parallel research threads
under sibling subdirectories::

    python <path-to-harness>/.harness/scripts/init_research_project.py --project ./hvg-baseline
    python <path-to-harness>/.harness/scripts/init_research_project.py --project ./dhvg-extension

Each thread gets its own `.research-harness` marker, its own docs/,
literature/, src/, outputs/, etc. — the harness scripts treat them as
independent projects.

Layout version: 3
"""

